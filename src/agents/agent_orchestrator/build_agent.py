    cypher_state = final_state.get("cypher_state")
    graph_state = final_state.get("graph_state")
    final_answer = final_state.get("final_response", None)

    # Display outputs
    if cypher_state and getattr(cypher_state, "query_results", None):
        print("\n=== Cypher Agent Response ===")
        print("Detected Intention:", getattr(cypher_state, "intent_detected", None))
        print("Matched Cyphers:", getattr(cypher_state, "matched_cyphers", None))
        print("Generated Cypher:", getattr(cypher_state, "cypher_generated", None))
        print("Corrected Cypher:", getattr(cypher_state, "cypher_corrected", None))
        print("Corrections Applied:", getattr(cypher_state, "cypher_corrections", None))
        print("Query Results:", getattr(cypher_state, "query_results", None))
        print("Final Answer:", final_answer)
    elif graph_state:
        print("\n=== Graph Agent Response (Fallback) ===")
        print("Expanded Nodes:", getattr(graph_state, "expanded_nodes", None))
        print("RAG Reviews:", getattr(graph_state, "rag_reviews", None))
        print("Final Answer:", final_answer)
    else:
        print("\nNo agent generated a reliable answer.")
        print("Final Answer:", final_answer)